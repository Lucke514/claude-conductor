import { describe, expect, it } from "vitest";
import { scrubCommand } from "../src/gh-scrub.js";
import { hasAttribution, stripAttribution, stripAttributionEscaped } from "../src/sanitize.js";

describe("stripAttribution (commit messages)", () => {
  it.each([
    ["Claude trailer", "feat: x\n\nBody.\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n", "feat: x\n\nBody.\n"],
    ["lowercase trailer", "fix: y\n\nco-authored-by: Someone <a@b.c>\n", "fix: y\n"],
    ["upper-case trailer, spaces", "fix: y\n\n  CO-AUTHORED-BY :  Bot <b@c>\n", "fix: y\n"],
    ["Codex trailer", "chore: z\n\nCo-authored-by: Codex <codex@openai.com>\n", "chore: z\n"],
    ["agy trailer", "chore: z\n\nCo-authored-by: Antigravity <agy@google.com>\n", "chore: z\n"],
    [
      "Claude Code footer + trailer",
      "feat: a\n\nDetails\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n",
      "feat: a\n\nDetails\n",
    ],
    ["Generated with without emoji", "x\n\nGenerated with [Claude Code](https://claude.ai/code)\n", "x\n"],
    ["Generated by Codex", "x\n\nGenerated by Codex\n", "x\n"],
    ["session trailer", "x\n\nClaude-Session: https://claude.ai/code/session_01AbC\n", "x\n"],
    ["bare session URL", "x\n\nhttps://claude.ai/code/session_01LhWPCd\n", "x\n"],
    ["multiple trailers mixed with a real one", "x\n\nSigned-off-by: Me <me@x>\nCo-authored-by: Bot <b@c>\nRefs: #12\n", "x\n\nSigned-off-by: Me <me@x>\nRefs: #12\n"],
    ["CRLF", "x\r\n\r\nCo-authored-by: Bot <b@c>\r\n", "x\r\n"],
    ["keeps git comments", "x\n\nCo-authored-by: a <b>\n# Please enter the commit message\n", "x\n\n# Please enter the commit message\n"],
  ])("%s", (_name, input, expected) => {
    expect(stripAttribution(input)).toBe(expected);
  });

  it("removes inline fragments and leaves normal text alone", () => {
    expect(stripAttribution("Done. 🤖 Generated with [Claude Code](https://claude.com/claude-code)")).toBe("Done.");
    const clean = "feat: generated parser\n\nGenerated with care by the team.\n";
    expect(stripAttribution(clean)).toBe(clean);
    expect(hasAttribution(clean)).toBe(false);
    expect(hasAttribution("a\n\nCo-authored-by: b <c>\n")).toBe(true);
  });

  it("handles bodies with literal \\n escapes", () => {
    expect(stripAttributionEscaped("Summary\\n\\n🤖 Generated with [Claude Code](https://claude.com/claude-code)")).toBe("Summary");
  });
});

describe("scrubCommand (PreToolUse Bash)", () => {
  it("ignores unrelated commands", () => {
    const r = scrubCommand("echo 'Co-authored-by: x'");
    expect(r.changed).toBe(false);
  });

  it("cleans a heredoc PR body", () => {
    const cmd = [
      `gh pr create --title "feat: x" --body "$(cat <<'EOF'`,
      "## Summary",
      "- did things",
      "",
      "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
      "",
      "https://claude.ai/code/session_01LhWPCdU7zWDMwGk7BvqXHt",
      "EOF",
      `)"`,
    ].join("\n");
    const r = scrubCommand(cmd);
    expect(r.changed).toBe(true);
    expect(r.command).toBe([`gh pr create --title "feat: x" --body "$(cat <<'EOF'`, "## Summary", "- did things", "EOF", `)"`].join("\n"));
  });

  it("cleans single-line --body with escaped newlines and gh pr edit", () => {
    const r = scrubCommand(`gh pr edit 12 --body "Fixes bug\\n\\n🤖 Generated with [Claude Code](https://claude.com/claude-code)"`);
    expect(r.command).toBe(`gh pr edit 12 --body "Fixes bug"`);
    const r2 = scrubCommand(`gh pr create -t x -b 'Body\\nCo-Authored-By: Claude <noreply@anthropic.com>'`);
    expect(r2.command).toBe(`gh pr create -t x -b 'Body'`);
  });

  it("rewrites --body-file to a cleaned temp copy without touching the original", () => {
    const files: Record<string, string> = { "body.md": "Text\n\nCo-authored-by: Bot <b@c>\n" };
    const written: string[] = [];
    const io = {
      readFile: (p: string) => files[p],
      writeTemp: (c: string) => {
        written.push(c);
        return "/tmp/clean body.md";
      },
    };
    const r = scrubCommand("gh pr create --title t --body-file body.md", io);
    expect(r.command).toBe("gh pr create --title t --body-file '/tmp/clean body.md'");
    expect(written).toEqual(["Text\n"]);
    expect(files["body.md"]).toContain("Co-authored-by");
    const r2 = scrubCommand('gh pr create -F "body.md"', io);
    expect(r2.command).toBe("gh pr create -F '/tmp/clean body.md'");
    expect(scrubCommand("gh pr create --body-file missing.md", io).changed).toBe(false);
  });

  it("cleans git commit heredoc messages too", () => {
    const cmd = `git commit -m "$(cat <<'EOF'\nfeat: x\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\nClaude-Session: https://claude.ai/code/session_01X\nEOF\n)"`;
    expect(scrubCommand(cmd).command).toBe(`git commit -m "$(cat <<'EOF'\nfeat: x\nEOF\n)"`);
  });
});
